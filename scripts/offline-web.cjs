const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const CACHE_PREFIX = "laviviane-app-shell-";
const STATIC_EXTENSIONS = new Set([
  ".avif",
  ".css",
  ".gif",
  ".ico",
  ".jpeg",
  ".jpg",
  ".js",
  ".json",
  ".otf",
  ".png",
  ".svg",
  ".ttf",
  ".wasm",
  ".webp",
  ".woff",
  ".woff2",
]);

function toPublicUrl(relativePath) {
  return `/${relativePath.split(path.sep).map(encodeURIComponent).join("/")}`;
}

function isStaticBundleAsset(relativePath) {
  const normalized = relativePath.split(path.sep).join("/");
  const isExpoOutput =
    normalized.startsWith("assets/") ||
    normalized.startsWith("_expo/") ||
    normalized.startsWith("fonts/");

  return isExpoOutput && STATIC_EXTENSIONS.has(path.extname(normalized).toLowerCase());
}

function collectStaticAssets(outputDirectory) {
  const matches = [];

  function visit(directory) {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const fullPath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        visit(fullPath);
      } else if (entry.isFile()) {
        const relativePath = path.relative(outputDirectory, fullPath);
        if (isStaticBundleAsset(relativePath)) matches.push(relativePath);
      }
    }
  }

  visit(outputDirectory);
  return matches.sort();
}

function sha256(bytes) {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

function buildManifest() {
  return {
    id: "/",
    name: "Laviviane | إدارة الفواتير",
    short_name: "Laviviane",
    description: "إدارة الطلبات والفواتير",
    start_url: "/",
    scope: "/",
    display: "standalone",
    orientation: "portrait",
    lang: "ar",
    dir: "rtl",
    theme_color: "#1A2744",
    background_color: "#F5F7FA",
    icons: [
      {
        src: "/app-icon.svg",
        sizes: "any",
        type: "image/svg+xml",
        purpose: "any maskable",
      },
    ],
  };
}

function buildWorkerSource(cacheName, staticPaths) {
  return `/* Generated by scripts/offline-web.cjs; do not edit this build output. */
"use strict";
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const CACHE_NAME = ${JSON.stringify(cacheName)};
const APP_SHELL = "/index.html";
const STATIC_PATHS = new Set(${JSON.stringify(staticPaths)});

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    await cache.addAll([APP_SHELL, "/manifest.webmanifest", "/app-icon.svg"]);
    const paths = Array.from(STATIC_PATHS);
    for (let index = 0; index < paths.length; index += 12) {
      await cache.addAll(paths.slice(index, index + 12));
    }
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const names = (await caches.keys()).filter((name) => name.startsWith(CACHE_PREFIX));
    const expired = names.slice(0, Math.max(0, names.length - 2));
    await Promise.all(expired.map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.status < 500) return response;
      } catch {}

      const cache = await caches.open(CACHE_NAME);
      return (await cache.match(APP_SHELL)) || Response.error();
    })());
    return;
  }

  if (!STATIC_PATHS.has(url.pathname) && url.pathname !== "/app-icon.svg" && url.pathname !== "/manifest.webmanifest") {
    return;
  }

  event.respondWith((async () => {
    const cacheNames = (await caches.keys())
      .filter((name) => name.startsWith(CACHE_PREFIX))
      .reverse();
    for (const name of cacheNames) {
      const response = await (await caches.open(name)).match(request);
      if (response) return response;
    }
    return fetch(request);
  })());
});
`;
}

function createOfflineSupport(outputDirectory, options = {}) {
  const root = path.resolve(outputDirectory);
  const indexPath = path.join(root, "index.html");
  if (!fs.existsSync(indexPath)) {
    throw new Error("Expo export must create static-build/index.html before offline support is generated.");
  }

  const iconSource = options.iconSource || path.resolve(__dirname, "../public/app-icon.svg");
  if (!fs.existsSync(iconSource)) throw new Error("The Laviviane app icon source is missing.");

  const iconDestination = path.join(root, "app-icon.svg");
  fs.copyFileSync(iconSource, iconDestination);

  const manifestContents = `${JSON.stringify(buildManifest(), null, 2)}\n`;
  fs.writeFileSync(path.join(root, "manifest.webmanifest"), manifestContents);

  const assetPaths = collectStaticAssets(root);
  const staticPaths = [...new Set(assetPaths.map(toPublicUrl))].sort();

  const versionHash = crypto.createHash("sha256");
  const fingerprintPaths = [...new Set(["index.html", "app-icon.svg", "manifest.webmanifest", ...assetPaths])].sort();
  let assetBytes = 0;

  for (const relativePath of fingerprintPaths) {
    const contents = fs.readFileSync(path.join(root, relativePath));
    assetBytes += contents.length;
    versionHash.update(relativePath);
    versionHash.update("\0");
    versionHash.update(sha256(contents));
    versionHash.update("\0");
  }

  const cacheName = `${CACHE_PREFIX}${versionHash.digest("hex").slice(0, 16)}`;
  fs.writeFileSync(
    path.join(root, "service-worker.js"),
    buildWorkerSource(cacheName, staticPaths)
  );
  fs.writeFileSync(
    path.join(root, "offline-register.js"),
    `"use strict";\nif ("serviceWorker" in navigator && window.isSecureContext) {\n` +
      `  window.addEventListener("load", function () {\n` +
      `    navigator.serviceWorker.register("/service-worker.js", { scope: "/" }).catch(function () {});\n` +
      `  }, { once: true });\n` +
      `}\n`
  );

  return {
    version: cacheName.slice(CACHE_PREFIX.length),
    assetCount: assetPaths.length + 2,
    assetBytes,
  };
}

module.exports = { createOfflineSupport, collectStaticAssets, isStaticBundleAsset };
